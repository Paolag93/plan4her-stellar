import{expect,test}from'@playwright/test'

test.describe('MVP Daily exact flow',()=>{
 test('DA01 Today uses canonical 390×844 structure',async({page})=>{
  await page.goto('/?qa=today')
  await expect(page.locator('[data-figma-node="4198:154"]')).toBeVisible()
  await expect(page.locator('.today-screen')).toHaveCSS('width','390px')
  await expect(page.locator('.today-screen')).toHaveCSS('height','844px')
  await expect(page.locator('.today-screen__scroll')).toHaveCSS('height','636px')
  await expect(page.locator('.today-date-strip')).toHaveCSS('height','64px')
  await expect(page.locator('.daily-phase-context')).toHaveCSS('height','224px')
 })
 test('date strip reproduces Tue and open weekend states',async({page})=>{
  await page.goto('/?qa=today')
  await page.getByRole('button',{name:/Tue 24/}).click()
  await expect(page.locator('[data-figma-node="4272:3513"]')).toBeVisible()
  await expect(page.getByText('Research notes')).toBeVisible()
  await page.getByRole('button',{name:/Sat 28/}).click()
  await expect(page.locator('[data-figma-node="4314:5535"]')).toBeVisible()
  await expect(page.getByRole('heading',{name:'Nothing scheduled for Saturday'})).toBeVisible()
 })
 test('Monday task completion uses only the Figma-defined states',async({page})=>{
  await page.goto('/?qa=today')
  await expect(page.getByRole('button',{name:'Mark Team meeting done',exact:true})).toHaveAttribute('aria-pressed','false')
  await page.getByRole('button',{name:'Mark Team meeting done',exact:true}).click()
  await expect(page.getByRole('button',{name:'Mark Team meeting incomplete',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-figma-node="4272:3858"]')).toBeVisible()
  await page.getByRole('button',{name:'Mark Buy groceries done',exact:true}).click()
  await expect(page.getByRole('button',{name:'Mark Buy groceries incomplete',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('[data-figma-node="4273:3226"]')).toBeVisible()
 })
 test('FAB reuses canonical Add task chooser',async({page})=>{
  await page.goto('/?qa=today')
  await page.getByRole('button',{name:'Add task'}).click()
  await expect(page.locator('[data-figma-node="4578:6158"]')).toBeVisible()
 })
 test('DA03 partial routes to RC05, not directly to a changed plan',async({page})=>{
  await page.goto('/?qa=today')
  await page.getByRole('button',{name:'Update progress'}).click()
  await expect(page.locator('[data-figma-node="4198:185"]')).toBeVisible()
  await page.getByRole('radio',{name:/Partially done/}).click()
  await expect(page.locator('[data-figma-node="4199:960"]')).toBeVisible()
  await page.getByRole('button',{name:'Continue'}).click()
  await expect(page.locator('[data-figma-node="4216:3809"]')).toBeVisible()
 })
 test('missed recovery preserves preview → apply → Undo grammar',async({page})=>{
  await page.goto('/?qa=complete-missed')
  await page.getByRole('button',{name:'Continue'}).click()
  await expect(page.locator('[data-figma-node="4198:197"]')).toBeVisible()
  await page.getByRole('button',{name:'Choose what happens next'}).click()
  await expect(page.locator('[data-figma-node="4198:207"]')).toBeVisible()
  await page.getByRole('button',{name:/Move later/}).click()
  await expect(page.locator('[data-figma-node="4199:1066"]')).toBeVisible()
  await page.getByRole('button',{name:'Preview changes'}).click()
  await expect(page.locator('[data-figma-node="4198:217"]')).toBeVisible()
  await page.getByRole('button',{name:'Apply change'}).click()
  await expect(page.locator('[data-figma-node="4198:227"]')).toBeVisible()
  await page.getByRole('button',{name:'Undo'}).click()
  await expect(page.locator('[data-figma-node="4198:154"]')).toBeVisible()
 })
 test('missed split and partial split keep distinct Figma previews',async({page})=>{
  await page.goto('/?qa=recovery-options-split')
  await expect(page.locator('[data-figma-node="4272:1884"]')).toBeVisible()
  await page.getByRole('button',{name:'Preview changes'}).click()
  await expect(page.locator('[data-figma-node="4379:5647"]')).toBeVisible()
  await expect(page.locator('.recovery-diff')).toHaveCSS('height','192px')
  await page.goto('/?qa=recovery-partial-split')
  await expect(page.locator('[data-figma-node="4272:1932"]')).toBeVisible()
  await page.getByRole('button',{name:'Preview changes'}).click()
  await expect(page.locator('[data-figma-node="4379:5875"]')).toBeVisible()
  await expect(page.locator('.recovery-diff')).toHaveCSS('height','200px')
 })
 test('More → Cycle context → Help follows Figma routes',async({page})=>{
  await page.goto('/?qa=more')
  await expect(page.locator('[data-figma-node="4198:298"]')).toBeVisible()
  await page.getByRole('button',{name:'Cycle context'}).click()
  await expect(page.locator('[data-figma-node="4250:4081"]')).toBeVisible()
  await page.getByRole('switch').click()
  await expect(page.locator('[data-figma-node="4272:3365"]')).toBeVisible()
  await page.getByRole('switch').click()
  await page.getByRole('button',{name:'How cycle context works'}).click()
  await expect(page.locator('[data-figma-node="4317:5697"]')).toBeVisible()
 })
 test('Cycle Context settings calendar is the settings variant',async({page})=>{
  await page.goto('/?qa=cycle-context')
  await page.getByRole('button',{name:'Last period started'}).click()
  await expect(page.locator('[data-figma-node="4565:6154"]')).toBeVisible()
  await expect(page.getByText('Selected: 16 Oct')).toBeVisible()
  await expect(page.getByRole('button',{name:'16'})).toHaveClass(/calendar-overlay__day--selected/)
 })
})

