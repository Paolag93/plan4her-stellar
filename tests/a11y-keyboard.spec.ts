test('plan edit selectors trap focus and expose updated selected values', async ({ page }) => {
  await page.goto('/?qa=plan-edit-overlay-prepare')
  const duration = page.getByRole('button', { name: 'Duration', exact: true, includeHidden: true })
  await checkDialogKeyboard(page, duration, 'Duration')
  const start = page.getByRole('button', { name: 'Start time', exact: true, includeHidden: true })
  await checkDialogKeyboard(page, start, 'Start time')
  await duration.press('Enter')
  await page.getByRole('dialog').getByRole('button', { name: '45 min', exact: true }).press('Enter')
  await expect(duration).toBeFocused()
  await duration.press('Enter')
  await expect(page.getByRole('dialog').getByRole('button', { name: '45 min', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('dialog').getByRole('button', { name: '90 min', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await page.keyboard.press('Escape')
  await start.press('Enter')
  await page.getByRole('dialog').getByRole('button', { name: '12:00 PM', exact: true }).press('Enter')
  await expect(start).toBeFocused()
  await start.press('Enter')
  await expect(page.getByRole('dialog').getByRole('button', { name: '12:00 PM', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Escape')
  await expect(page.locator('[inert]')).toHaveCount(0)
})
