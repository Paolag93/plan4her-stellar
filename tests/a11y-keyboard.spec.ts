test('choice cards have one Tab stop and arrow keys select and wrap', async ({ page }) => {
  await page.goto('/?qa=start')
  await page.getByRole('button', { name: 'Build my first week' }).click()
  await page.getByRole('button', { name: 'Continue', exact: true }).click()
  const group = page.getByRole('radiogroup', { name: 'Cycle context' })
  const radios = group.getByRole('radio')
  await expect(group.locator('[tabindex="0"]')).toHaveCount(1)
  await expect(radios.first()).toHaveAttribute('tabindex', '0')
  await radios.first().focus()
  await page.keyboard.press('ArrowDown')
  await expect(radios.nth(1)).toBeFocused()
  await expect(radios.nth(1)).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('End')
  await expect(radios.last()).toBeFocused()
  await expect(radios.last()).toHaveAttribute('aria-checked', 'true')
  await page.keyboard.press('ArrowRight')
  await expect(radios.first()).toBeFocused()
  await expect(radios.first()).toHaveAttribute('aria-checked', 'true')
  await expect(group.locator('[tabindex="0"]')).toHaveCount(1)
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Continue without cycle context' })).toBeFocused()
})

